/// Whether `c` is in `table`: a character outside the Basic Multilingual Plane, two
/// surrogate code units, never is.
pub(crate) fn contains(table: &[(u16, u16)], c: char) -> bool {
    let Ok(unit) = u16::try_from(u32::from(c)) else {
        return false;
    };
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < unit {
                std::cmp::Ordering::Less
            } else if lo > unit {
                std::cmp::Ordering::Greater
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Whether the JDK's DOM (Xerces, XML 1.0: `XMLChar.isValidNCName`) accepts `name` as a
/// part of a qualified name (a prefix or a local name), or, with `colon`, as a name
/// (`XMLChar.isValidName`: a processing instruction target): the tables of ph-commons,
/// the colon allowed in a name, and no character outside the Basic Multilingual Plane
/// (Xerces takes surrogate code units for invalid).
pub(crate) fn xerces_accepts(name: &str, colon: bool) -> bool {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return false;
    };
    let ok = |c: char, table: &[(u16, u16)]| {
        u32::from(c) <= 0xFFFF
            && !matches!(u32::from(c), 0xD800..=0xDFFF)
            && ((colon && c == ':') || !contains(table, c))
    };
    ok(first, INVALID_NAME_START) && chars.all(|c| ok(c, INVALID_NAME))
}

#[cfg(test)]
mod tests {
    use std::fmt::Write as _;

    use super::*;

    /// The ranges of the code units (as characters, surrogates aside) for which `invalid`
    /// holds, in the format of `tests/data/xml10-chars.txt`.
    fn ranges(table: &str, invalid: &dyn Fn(u32) -> bool) -> String {
        let mut out = String::new();
        let mut first: Option<u32> = None;
        for unit in 0..=0x1_0000_u32 {
            let bad = unit <= 0xFFFF && invalid(unit);
            match (bad, first) {
                (true, None) => first = Some(unit),
                (false, Some(start)) => {
                    let _ = writeln!(out, "{table} {start:04X} {:04X}", unit - 1);
                    first = None;
                }
                _ => {}
            }
        }
        out
    }

    fn char_of(unit: u32) -> Option<char> {
        char::from_u32(unit)
    }

    #[test]
    fn char_tables() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("tests")
            .join("data")
            .join("xml10-chars.txt");
        let Ok(expected) = std::fs::read_to_string(&path) else {
            eprintln!("SKIPPED: no {} (not in the package)", path.display());
            return;
        };
        let surrogate = |u: u32| (0xD800..=0xDFFF).contains(&u);
        let value = |u: u32| char_of(u).is_some_and(|c| contains(INVALID_VALUE, c));
        let mut ours = String::new();
        ours += &ranges("name-start", &|u| {
            char_of(u).is_some_and(|c| contains(INVALID_NAME_START, c))
        });
        ours += &ranges("name", &|u| {
            char_of(u).is_some_and(|c| contains(INVALID_NAME, c))
        });
        ours += &ranges("text", &value);
        ours += &ranges("attribute-value", &value);
        ours += &ranges("cdata", &value);
        let xerces = |u: u32, colon: bool, prefix: &str| {
            surrogate(u)
                || char_of(u).is_none_or(|c| !xerces_accepts(&format!("{prefix}{c}"), colon))
        };
        ours += &ranges("xerces-name-start", &|u| xerces(u, false, ""));
        ours += &ranges("xerces-name", &|u| xerces(u, false, "a"));
        ours += &ranges("xerces-target-start", &|u| xerces(u, true, ""));
        ours += &ranges("xerces-target", &|u| xerces(u, true, "a"));
        let word = |ok: bool| if ok { "valid" } else { "invalid" };
        let _ = writeln!(
            ours,
            "xerces-supplementary-start {}",
            word(xerces_accepts("\u{10000}", false))
        );
        let _ = writeln!(
            ours,
            "xerces-supplementary {}",
            word(xerces_accepts("a\u{10000}", false))
        );
        let _ = writeln!(
            ours,
            "xerces-target-supplementary-start {}",
            word(xerces_accepts("\u{10000}", true))
        );
        let _ = writeln!(
            ours,
            "xerces-target-supplementary {}",
            word(xerces_accepts("a\u{10000}", true))
        );
        assert!(
            ours == expected,
            "the tables differ from {}",
            path.display()
        );
    }
}
